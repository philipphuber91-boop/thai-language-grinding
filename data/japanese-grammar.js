        alternative,
        possessionLead: "Du kannst außerdem Zugehörigkeit und Besitz ausdrücken:",
        possession,
        progressTitle: "📈 DEIN FORTSCHRITT",
        progress: `${number} / 1.000 Sätze`,
        progressSummary: `${number / 10} % von Grammatikboss #1 geschafft.`,
