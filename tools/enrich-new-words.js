const errors = [];
for (const [thai, translit, de, sylTh, sylTr] of newGlossaryEntries) {
    const sTh = sylTh.split('|');
    const sTr = sylTr.split('|');
    if (sTh.join('') !== thai) {
        errors.push(`Syllable mismatch for ${thai}: "${sTh.join('')}" !== "${thai}"`);
    }
    if (sTh.length !== sTr.length) {
        errors.push(`Length mismatch for ${thai}: ${sTh.length} !== ${sTr.length}`);
    }
}

if (errors.length > 0) {
    console.error('Validation errors found:');
    errors.forEach(e => console.error(' - ' + e));
    process.exit(1);
}

