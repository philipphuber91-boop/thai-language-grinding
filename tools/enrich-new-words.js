function injectWords() {
    let content = fs.readFileSync(WORDS_FILE, 'utf8');

    // Filter out any already present
    const entriesToInject = newGlossaryEntries.filter(([thai]) => {
        return !content.includes(`["${thai}",`);
    });

    console.log(`Injecting ${entriesToInject.length} new words...`);
    if (entriesToInject.length === 0) return;

    const marker = '    const rawWords = [\n';
    const markerWin = '    const rawWords = [\r\n';
    const isWin = content.includes(markerWin);
    const useMarker = isWin ? markerWin : marker;
    const nl = isWin ? '\r\n' : '\n';

    const idx = content.indexOf(useMarker);
    if (idx === -1) {
        throw new Error('Could not find rawWords marker in thailand-quiz-words.js');
    }

    const insertIdx = idx + useMarker.length;
    let block = '';
    for (const [thai, translit, de, sylTh, sylTr] of entriesToInject) {
        block += `        [${JSON.stringify(thai)},${JSON.stringify(translit)},${JSON.stringify(de)},${JSON.stringify(sylTh)},${JSON.stringify(sylTr)}],${nl}`;
    }

    content = content.slice(0, insertIdx) + block + content.slice(insertIdx);
    fs.writeFileSync(WORDS_FILE, content, 'utf8');
    console.log('Successfully updated thailand-quiz-words.js!');
}

injectWords();
